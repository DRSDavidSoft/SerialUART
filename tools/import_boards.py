"""Validate a local SimplySerial boards.json and generate an offline C catalog.

No network operations or runtime Python dependency. Review upstream changes and
retain data/SIMPLYSERIAL-LICENSE.txt when refreshing the catalog.
"""
import argparse
import hashlib
import json
import pathlib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=pathlib.Path)
parser.add_argument("--output", type=pathlib.Path, default=pathlib.Path("cli/boards.inc"))
args = parser.parse_args()
raw = args.source.read_bytes()
if len(raw) > 2_000_000:
    raise SystemExit("Catalog exceeds 2 MB")
data = json.loads(raw)
rows = data["boards"]
if not isinstance(rows, list) or len(rows) > 4096:
    raise SystemExit("Invalid board count")


def name(s):
    if not isinstance(s, str) or len(s.encode("utf-8")) > 240 or any(ord(c) < 32 for c in s):
        raise SystemExit("Invalid catalog name")
    return json.dumps(s, ensure_ascii=False)


result = ["/* Generated by tools/import_boards.py; data copyright Edward Wright.",
          " * MIT notice: data/SIMPLYSERIAL-LICENSE.txt.",
          f" * Source SHA-256: {hashlib.sha256(raw).hexdigest()} */",
          "static const sc_board_entry board_data[]={"]
for row in rows:
    vid, pid = int(row["vid"], 16), int(row["pid"], 16)
    if not 0 < vid <= 65535 or not 0 < pid <= 65535:
        raise SystemExit("Invalid USB ID")
    result.append(f'    {{0x{vid:04X},0x{pid:04X},{name(row["make"])},{name(row["model"])}}},')
result += ["};", "static const sc_vendor_entry vendor_data[]={"]
for row in data["vendors"]:
    vid = int(row["vid"], 16)
    if not 0 < vid <= 65535:
        raise SystemExit("Invalid vendor ID")
    result.append(f'    {{0x{vid:04X},{name(row["make"])}}},')
result += ["};", ""]
args.output.write_text("\n".join(result), encoding="utf-8")
print(f"Imported {len(rows)} boards from SHA-256 {hashlib.sha256(raw).hexdigest()}")
